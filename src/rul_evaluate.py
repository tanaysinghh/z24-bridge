import json

import numpy as np
from scipy.special import softmax
from scipy.stats import kendalltau, spearmanr

from src import rul
from src.ensemble.stack import segment_logp
from src.taxonomy import CLASS_NAMES, DSI, TIERS, tier_for
from src.train.common import MODELS_DIR, RESULTS_DIR

SEEDS = [42, 1, 2]


def recording_probs(window_logp, seg):
    seg_ids, summed = segment_logp(window_logp, seg)
    counts = np.array([(seg == s).sum() for s in seg_ids])[:, None]
    return seg_ids, softmax(summed / counts, axis=1)


def evaluate(method, seed, split):
    with np.load(MODELS_DIR / "final" / f"ensemble_preds_s{seed}.npz") as f:
        logp, seg, y = f[f"{split}_{method}"].astype(np.float64), f[f"{split}_window_segment_id"], f[f"{split}_y"]
    seg_ids, probs = recording_probs(logp, seg)
    true_c = np.array([y[seg == s][0] for s in seg_ids])
    true_dsi = np.asarray(DSI)[true_c]
    pred_dsi = rul.expected_dsi(probs)
    true_tier = np.array([tier_for(d) for d in true_dsi])
    pred_tier = np.array([tier_for(d) for d in pred_dsi])
    rho, rho_p = spearmanr(pred_dsi, true_dsi)
    tau, tau_p = kendalltau(pred_dsi, true_dsi)
    per_class = {}
    for c in range(len(CLASS_NAMES)):
        m = true_c == c
        per_class[c] = {"true_dsi": DSI[c], "mean_pred_dsi": float(pred_dsi[m].mean()), "sd_pred_dsi": float(pred_dsi[m].std())}
    return {
        "n_recordings": int(len(seg_ids)),
        "spearman_rho": float(rho),
        "spearman_p": float(rho_p),
        "kendall_tau": float(tau),
        "kendall_p": float(tau_p),
        "dsi_mae": float(np.abs(pred_dsi - true_dsi).mean()),
        "tier_accuracy": float((pred_tier == true_tier).mean()),
        "tier_within_one": float((np.abs(pred_tier - true_tier) <= 1).mean()),
        "per_class": per_class,
    }, seg_ids, probs, true_c


def rul_examples(probs, true_c):
    out = {}
    for c in range(len(CLASS_NAMES)):
        idx = np.flatnonzero(true_c == c)
        ests = [rul.estimate(probs[i], seed=int(i)) for i in idx]
        out[c] = {
            "median_rul_years": float(np.median([e["rul_years"]["median"] for e in ests])),
            "median_lower": float(np.median([e["rul_years"]["lower"] for e in ests])),
            "median_upper": float(np.median([e["rul_years"]["upper"] for e in ests])),
        }
    return out


def main():
    ensemble = json.loads((RESULTS_DIR / "ensemble.json").read_text())
    method = ensemble["primary_method"]
    per_seed = {}
    for seed in SEEDS:
        per_seed[str(seed)] = {}
        for split in ("val", "test"):
            per_seed[str(seed)][split], _, probs, true_c = evaluate(method, seed, split)
            if seed == SEEDS[0] and split == "test":
                examples = rul_examples(probs, true_c)

    def agg(split, key):
        v = np.array([per_seed[s][split][key] for s in per_seed])
        return float(v.mean()), float(v.std())

    summary = {f"{split}_{k}": agg(split, k) for split in ("val", "test") for k in ("spearman_rho", "kendall_tau", "dsi_mae", "tier_accuracy", "tier_within_one")}
    report = {
        "method": method,
        "note": "Z24 has no remaining-life ground truth. These numbers only measure how well the predicted Damage Severity Index follows the severity ordering defined in docs/rul_method.md. They do not validate the RUL estimates in years.",
        "dsi_mapping": {CLASS_NAMES[c]: DSI[c] for c in range(len(DSI))},
        "tiers": TIERS,
        "rul_model": rul.DEFAULTS,
        "per_seed": per_seed,
        "summary": summary,
        "test_rul_by_true_class_seed42": examples,
        "deterministic_curve": rul.deterministic_curve(),
    }
    (RESULTS_DIR / "rul.json").write_text(json.dumps(report, indent=2))
    s42 = per_seed[str(SEEDS[0])]["test"]
    lines = [
        "# DSI and RUL validation",
        "",
        "Generated by `python -m src.rul_evaluate`. " + report["note"],
        "",
        f"Input: recording-level class probabilities of the primary flat ensemble ({method}). Mean +- std over seeds {', '.join(per_seed)}.",
        "",
        "| Metric | Validation (setup 7) | Test (setups 8-9) |",
        "|---|---|---|",
    ]
    names = {"spearman_rho": "Spearman rank correlation, predicted vs defined DSI", "kendall_tau": "Kendall tau", "dsi_mae": "Mean absolute DSI error", "tier_accuracy": "Severity-tier accuracy (5 tiers)", "tier_within_one": "Tier within one step"}
    for k, label in names.items():
        v, t = summary[f"val_{k}"], summary[f"test_{k}"]
        lines.append(f"| {label} | {v[0]:.3f} +- {v[1]:.3f} | {t[0]:.3f} +- {t[1]:.3f} |")
    lines += ["", "## Per scenario, test, seed 42", "", "| Label | Scenario | Defined DSI | Mean predicted DSI | Median RUL (years) | Median 90% interval |", "|---|---|---|---|---|---|"]
    for c, name in enumerate(CLASS_NAMES):
        pc, ex = s42["per_class"][c], examples[c]
        lines.append(f"| {c} | {name} | {pc['true_dsi']:.2f} | {pc['mean_pred_dsi']:.2f} +- {pc['sd_pred_dsi']:.2f} | {ex['median_rul_years']:.0f} | {ex['median_lower']:.0f} - {ex['median_upper']:.0f} |")
    (RESULTS_DIR / "rul.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
