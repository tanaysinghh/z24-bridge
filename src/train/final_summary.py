import json

import numpy as np

from src.taxonomy import CLASS_NAMES
from src.train.common import RESULTS_DIR

ARCHS = [("wavenet", "WaveNet"), ("inceptiontime", "InceptionTime"), ("minirocket", "MiniRocket")]
SEEDS = [42, 1, 2]
BASELINE_FILES = {42: "{a}.json", 1: "{a}_seed1.json", 2: "{a}_seed2.json"}
KEYS = [(s, k) for s in ("val", "test") for k in ("window_acc", "segment_acc", "window_macro_f1", "segment_macro_f1")]


def stats(runs):
    out = {}
    for split, key in KEYS:
        v = np.array([r["results"][split][key] for r in runs]) * 100
        out[f"{split}_{key}"] = [float(v.mean()), float(v.std())]
    return out


def recall(run):
    cm = np.array(run["results"]["test"]["confusion_segment"], dtype=float)
    return (cm.diagonal() / cm.sum(1)).tolist()


def config(run):
    a = run.get("args", {})
    keep = ("data", "epochs", "lr", "weight_decay", "dropout", "jitter", "scale", "time_warp", "mixup", "alpha_mode", "label_smoothing", "crops_per_segment")
    cfg = {k: a[k] for k in keep if k in a}
    if "ridge_alpha" in run:
        cfg["ridge_alpha"] = run["ridge_alpha"]
    return cfg


def main():
    summary, baseline, detail = {}, {}, {}
    for key, name in ARCHS:
        runs = [json.loads((RESULTS_DIR / "final" / f"{key}_s{s}.json").read_text()) for s in SEEDS]
        base = [json.loads((RESULTS_DIR / BASELINE_FILES[s].format(a=key)).read_text()) for s in SEEDS]
        summary[key] = stats(runs)
        baseline[key] = stats(base)
        detail[key] = {
            "name": name,
            "parameters": runs[0]["parameters"],
            "in_channels": runs[0].get("in_channels", 5 if "22-26" in runs[0]["data"] else 1),
            "config": config(runs[0]),
            "train_minutes_seed42": runs[0]["train_seconds"] / 60,
            "best_epoch_seed42": runs[0].get("best_epoch"),
            "test_recall_segment_seed42": recall(runs[0]),
        }
    payload = {"seeds": SEEDS, "class_names": CLASS_NAMES, "summary": summary, "review2_baseline": baseline, "models": detail}
    (RESULTS_DIR / "final_models.json").write_text(json.dumps(payload, indent=2))
    lines = [
        "# Final base models",
        "",
        "Generated by `python -m src.train.final_summary`. Mean +- std over seeds 42, 1, 2. Review 2 baseline = single channel 22, original protocol.",
        "",
        "| Model | Input | Val window | Val recording | Test window | Test recording | Test recording macro-F1 | Review 2 test recording |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for key, name in ARCHS:
        s, b, d = summary[key], baseline[key], detail[key]
        f = lambda p: f"{p[0]:.1f} +- {p[1]:.1f}"
        lines.append(
            f"| {name} | {d['in_channels']} ch | {f(s['val_window_acc'])} | {f(s['val_segment_acc'])} | {f(s['test_window_acc'])} | "
            f"{f(s['test_segment_acc'])} | {f(s['test_segment_macro_f1'])} | {f(b['test_segment_acc'])} |"
        )
    (RESULTS_DIR / "final_models.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
